import fs from "node:fs";
import path from "node:path";
import type { AstroIntegration } from "astro";
import siteConfig, { comment as enabled } from "../../site.config";

/**
 * Astro integration that switches the comment system between static and Cloudflare SSR modes based on `site.config.ts`.
 */
export default function commentIntegration(): AstroIntegration {
	const actionsEntry = path.resolve("src/actions/index.ts");
	const actionsStub = `// Generated by ThoughtLite. Changes to this file will be overwritten.
// The integration removes this file when comments are disabled.
// Register custom SSR actions in src/actions/server.ts.
export { server } from "./server";
`;

	// Sync `src/actions/index.ts` during config evaluation before Astro scans it in `runHookConfigSetup`.
	// Only write when content differs to avoid triggering unnecessary dev server restarts.
	if (enabled) {
		if (!fs.existsSync(actionsEntry) || fs.readFileSync(actionsEntry, "utf-8") !== actionsStub) {
			fs.writeFileSync(actionsEntry, actionsStub, "utf-8");
		}
	} else if (fs.existsSync(actionsEntry)) {
		fs.rmSync(actionsEntry);
	}

	return {
		name: "thought-lite-comment",
		hooks: {
			"astro:config:setup": ({ config, addWatchFile, injectRoute }) => {
				// Watch `site.config.ts` so toggling `comment.enable` restarts the dev server automatically.
				addWatchFile(new URL("./site.config.ts", config.root));

				if (!enabled) return;

				// Register SSR-only routes kept outside `src/pages/` so static builds do not scan them.
				injectRoute({
					pattern: "/@/depart",
					entrypoint: "./src/comment/@/depart.ts",
					prerender: false
				});
				injectRoute({
					pattern: "/@/reach/[provider]",
					entrypoint: "./src/comment/@/reach/[provider].ts",
					prerender: false
				});
				for (const locale of siteConfig.i18n.locales) {
					const prefix = locale === siteConfig.i18n.defaultLocale ? "" : `/${locale}`;
					injectRoute({
						pattern: `${prefix}/email`,
						entrypoint: "./src/comment/email/index.astro",
						prerender: false
					});
					injectRoute({
						pattern: `${prefix}/email/unsubscribe`,
						entrypoint: "./src/comment/email/unsubscribe.astro",
						prerender: false
					});
				}
			},
			"astro:config:done": ({ config, injectTypes }) => {
				if (enabled) return;

				// Keep `astro check` working in static mode even when `src/actions/index.ts` is absent.
				const actionsPath = JSON.stringify(path.resolve("src/actions/server.ts"));
				injectTypes({
					filename: "actions.d.ts",
					content: `declare module "astro:actions" {\n\texport const actions: typeof import(${actionsPath})["server"];\n}\n`
				});

				// Provide fallback Cloudflare runtime types when the Cloudflare adapter and `wrangler types` are absent.
				const typesContent = [
					"declare namespace App {",
					"\tinterface Locals {",
					"\t\tcfContext: { waitUntil(promise: Promise<unknown>): void };",
					"\t}",
					"}"
				];

				if (!fs.existsSync(new URL("./worker-configuration.d.ts", config.root))) {
					typesContent.push('declare module "cloudflare:workers" {', "\texport const env: Record<string, any>;", "}");
				}

				injectTypes({
					filename: "comment-fallback.d.ts",
					content: `${typesContent.join("\n")}\n`
				});
			}
		}
	};
}
